#!/usr/bin/env python3

from __future__ import annotations

import argparse
import re
from pathlib import Path


MARKER = "/* Generated by build/mkmbedtls4wrappers.py. */\n"
INCLUDE_RE = re.compile(r'#include\s+"([^"]+)"')
WRAPPER_SUBDIR = "third_party/mbedtls4/generated"


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def generated_no_static_source(root: Path) -> Path:
    return root / WRAPPER_SUBDIR / "psa_crypto_driver_wrappers_no_static.c"


def source_roots(root: Path) -> list[Path]:
    return [
        root / "third_party/mbedtls4/library",
        root / "third_party/mbedtls4/tf-psa-crypto/core",
        root / "third_party/mbedtls4/tf-psa-crypto/drivers/builtin/src",
        root / "third_party/mbedtls4/tf-psa-crypto/extras",
        root / "third_party/mbedtls4/tf-psa-crypto/platform",
        root / "third_party/mbedtls4/tf-psa-crypto/utilities",
    ]


def search_dirs(root: Path) -> list[Path]:
    return [
        root / "third_party/mbedtls4/include",
        root / "third_party/mbedtls4/library",
        root / "third_party/mbedtls4/tf-psa-crypto/include",
        root / "third_party/mbedtls4/tf-psa-crypto/core",
        root / "third_party/mbedtls4/tf-psa-crypto/dispatch",
        root / "third_party/mbedtls4/tf-psa-crypto/drivers/builtin/include",
        root / "third_party/mbedtls4/tf-psa-crypto/drivers/builtin/src",
        root / "third_party/mbedtls4/tf-psa-crypto/drivers/everest/include",
        root / "third_party/mbedtls4/tf-psa-crypto/drivers/p256-m",
        root / "third_party/mbedtls4/tf-psa-crypto/drivers/pqcp/include",
        root / "third_party/mbedtls4/tf-psa-crypto/drivers/pqcp/src",
        root / "third_party/mbedtls4/tf-psa-crypto/extras",
        root / "third_party/mbedtls4/tf-psa-crypto/framework/tests/include",
        root / "third_party/mbedtls4/tf-psa-crypto/platform",
        root / "third_party/mbedtls4/tf-psa-crypto/utilities",
        root / "third_party/mbedtls4/tests/include/alt-dummy",
        root / "third_party/mbedtls4/tf-psa-crypto/tests/include/alt-dummy",
    ]


def iter_start_files(root: Path) -> list[Path]:
    files: list[Path] = []
    for src_root in source_roots(root):
        for path in src_root.rglob("*"):
            if path.suffix in {".c", ".h"}:
                files.append(path)
    return sorted(files)


def iter_active_includes(text: str) -> list[str]:
    return INCLUDE_RE.findall(text)


def resolve_include(include: str, path: Path, dirs: list[Path]) -> Path | None:
    candidate = path.parent / include
    if candidate.exists():
        return candidate
    for directory in dirs:
        candidate = directory / include
        if candidate.exists():
            return candidate
    return None


def is_generated_wrapper(path: Path) -> bool:
    try:
        return path.read_text().startswith(MARKER)
    except OSError:
        return False


def walk_reachable_headers(root: Path) -> tuple[set[str], dict[str, str]]:
    dirs = search_dirs(root)
    seen: set[str] = set()
    headers: set[str] = set()
    wrappers: dict[str, str] = {}
    stack = iter_start_files(root)
    while stack:
        path = stack.pop()
        key = path.as_posix()
        if key in seen:
            continue
        seen.add(key)
        try:
            text = path.read_text(errors="ignore")
        except OSError:
            continue
        for include in iter_active_includes(text):
            if "libtestdriver1-" in include:
                continue
            resolved = resolve_include(include, path, dirs)
            if resolved and resolved.suffix == ".h":
                resolved_key = resolved.as_posix()
                headers.add(resolved.relative_to(root).as_posix())
                if resolved_key not in seen:
                    stack.append(resolved)
            if include.startswith("../"):
                continue
            wrapper = root / include
            if wrapper.exists() and not is_generated_wrapper(wrapper):
                continue
            if resolved:
                wrappers.setdefault(include, resolved.relative_to(root).as_posix())
    return headers, wrappers


def compute_wrappers(root: Path) -> dict[str, str]:
    wrappers = walk_reachable_headers(root)[1]
    wrappers.setdefault(
        "psa/error.h",
        "third_party/mbedtls4/tf-psa-crypto/include/psa/crypto_types.h",
    )
    wrappers.setdefault(
        "psa/internal_trusted_storage.h",
        "third_party/mbedtls4/tf-psa-crypto/core/psa_crypto_its.h",
    )
    wrappers.setdefault(
        "p256-m_driver_entrypoints.h",
        "third_party/mbedtls4/tf-psa-crypto/drivers/p256-m/p256-m_driver_entrypoints.h",
    )
    return wrappers


def compute_headers(root: Path) -> set[str]:
    return walk_reachable_headers(root)[0]


def generate(root: Path) -> None:
    for include, target in compute_wrappers(root).items():
        wrapper = root / WRAPPER_SUBDIR / include
        wrapper.parent.mkdir(parents=True, exist_ok=True)
        content = (
            MARKER
            + "#define COSMO_MBEDTLS4_WRAP(x) x\n"
            + f'#include COSMO_MBEDTLS4_WRAP("{target}")\n'
            + "#undef COSMO_MBEDTLS4_WRAP\n"
        )
        if wrapper.exists():
            try:
                existing = wrapper.read_text()
            except OSError:
                existing = ""
            if existing == content:
                continue
            if not existing.startswith(MARKER):
                raise SystemExit(f"refusing to overwrite non-generated file: {wrapper}")
        wrapper.write_text(content)

    source = (
        root
        / "third_party/mbedtls4/tf-psa-crypto/core/psa_crypto_driver_wrappers_no_static.c"
    )
    generated = generated_no_static_source(root)
    generated.parent.mkdir(parents=True, exist_ok=True)
    content = source.read_text()
    content = content.replace(
        '#include "../drivers/p256-m/p256-m_driver_entrypoints.h"',
        '#include "p256-m_driver_entrypoints.h"',
    )
    if not content.startswith("/*"):
        content = MARKER + content
    else:
        content = MARKER + content
    generated.write_text(content)


def clean_wrappers(root: Path) -> None:
    """Remove only the generated wrapper .h files (safe to call post-build)."""
    generated_dir = root / WRAPPER_SUBDIR
    if not generated_dir.exists():
        return
    for wrapper in sorted(generated_dir.rglob("*.h"), key=lambda p: len(p.parts), reverse=True):
        try:
            if wrapper.read_text().startswith(MARKER):
                wrapper.unlink()
        except OSError:
            pass
    for directory in sorted(generated_dir.rglob("*"), key=lambda p: len(p.parts), reverse=True):
        if directory.is_dir():
            try:
                directory.rmdir()
            except OSError:
                pass
    try:
        generated_dir.rmdir()
    except OSError:
        pass


def clean(root: Path) -> None:
    clean_wrappers(root)
    generated = generated_no_static_source(root)
    if generated.exists():
        generated.unlink()
    for directory in [generated.parent]:
        try:
            directory.rmdir()
        except OSError:
            pass


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--print-targets", action="store_true")
    parser.add_argument("--print-headers", action="store_true")
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--clean-wrappers", action="store_true")
    parser.add_argument("--clean", action="store_true")
    args = parser.parse_args()

    root = repo_root()
    wrappers = compute_wrappers(root)
    if args.print_targets:
        print(" ".join(sorted(f"{WRAPPER_SUBDIR}/{inc}" for inc in wrappers)))
    if args.print_headers:
        print(" ".join(sorted(compute_headers(root))))
    if args.generate:
        generate(root)
    if args.clean_wrappers:
        clean_wrappers(root)
    if args.clean:
        clean(root)
    if not (args.print_targets or args.print_headers or args.generate or args.clean_wrappers or args.clean):
        parser.error("choose an action")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
